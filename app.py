def precision_recall_at_k(predictions, k=10, threshold=4.0):
    """Compute avg Precision@K and Recall@K."""
    user_preds = defaultdict(list)
    for p in predictions:
        user_preds[p.uid].append((p.est, p.r_ui))
    precisions, recalls = [], []
    for uid, est_true in user_preds.items():
        est_true.sort(key=lambda x: x[0], reverse=True)
        topk = est_true[:k]
        n_rel = sum(1 for (_, true) in est_true if true >= threshold)
        n_rec_k = sum(1 for (_, true) in topk if true >= threshold)
        precisions.append(n_rec_k / k)
        recalls.append(n_rec_k / n_rel if n_rel > 0 else 0.0)
    return np.mean(precisions), np.mean(recalls)

def ndcg_at_k(predictions, k=10, threshold=4.0):
    """Compute avg NDCG@K."""
    user_preds = defaultdict(list)
    for p in predictions:
        user_preds[p.uid].append((p.est, p.r_ui))
    ndcgs = []
    for uid, est_true in user_preds.items():
        est_true.sort(key=lambda x: x[0], reverse=True)
        dcg = 0.0
        for i, (_, true) in enumerate(est_true[:k], start=1):
            rel = 1 if true >= threshold else 0
            dcg += (2**rel - 1) / log2(i + 1)
        ideal_rels = sorted([1 if t >= threshold else 0 for (_, t) in est_true], reverse=True)
        idcg = sum((2**rel - 1) / log2(i + 1) for i, rel in enumerate(ideal_rels[:k], start=1))
        ndcgs.append(dcg / idcg if idcg > 0 else 0.0)
    return np.mean(ndcgs)

