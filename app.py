def recommend_movies(user_id, N=10, model='svd'):
    """
    Return top-N recommended movies for a given user.
    model: 'svd' (matrix factorization) or 'item' (item-based CF)
    """
    if model == 'svd':
        return recommend_svd(user_id, N)
    elif model == 'item':
        return recommend_itemcf(user_id, N)
    else:
        raise ValueError("model must be 'svd' or 'item'")

