# -- imports
import pandas as pd
import numpy as np
from sklearn.metrics.pairwise import cosine_similarity
from surprise import Dataset, Reader, SVD
from surprise.model_selection import train_test_split

# -- load data
ratings = pd.read_csv('ml-latest-small/ratings.csv')
movies  = pd.read_csv('ml-latest-small/movies.csv')

print("ratings:", ratings.shape)
print("movies :", movies.shape)

# -- quick maps
movieid2title = dict(zip(movies.movieId, movies.title))
all_movie_ids = movies.movieId.unique().tolist()

# -- build user-item matrix for Item-CF
R = ratings.pivot_table(index='userId', columns='movieId', values='rating').fillna(0)
R_matrix = R.values
item_ids = R.columns.tolist()

# -- item similarity (cosine)
item_sim = cosine_similarity(R_matrix.T)
item_sim_df = pd.DataFrame(item_sim, index=item_ids, columns=item_ids)

def recommend_itemcf(user_id, N=10):
    if user_id not in R.index:
        return []
    user_ratings = R.loc[user_id]
    rated_items = user_ratings[user_ratings > 0].index.tolist()
    if len(rated_items) == 0:
        return []
    sim_sub = item_sim_df.loc[rated_items]
    weights = sim_sub.T.dot(user_ratings[rated_items].values)
    denom = sim_sub.abs().sum(axis=0).replace(0, np.nan)
    scores = weights / denom
    scores = scores.drop(labels=rated_items, errors='ignore')
    scores = scores.dropna()
    top = scores.sort_values(ascending=False).head(N)
    return [(int(mid), movieid2title[int(mid)], float(score)) for mid, score in top.items()]

# -- Surprise SVD model
reader = Reader(rating_scale=(0.5, 5.0))
data = Dataset.load_from_df(ratings[['userId','movieId','rating']], reader)
trainset, testset = train_test_split(data, test_size=0.2, random_state=42)

algo = SVD(n_factors=50, n_epochs=20, random_state=42)
algo.fit(trainset)

def recommend_svd(user_id, N=10):
    rated = set(ratings[ratings.userId==user_id].movieId.tolist())
    candidates = [mid for mid in all_movie_ids if mid not in rated]
    preds = []
    for mid in candidates:
        pred = algo.predict(user_id, mid)
        preds.append((mid, pred.est))
    preds.sort(key=lambda x: x[1], reverse=True)
    top = preds[:N]
    return [(int(mid), movieid2title[int(mid)], float(score)) for mid, score in top]

